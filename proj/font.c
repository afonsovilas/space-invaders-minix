#define FONT_FIRST 0x20u
#define FONT_LAST  0x5Au

void font_draw_char(int x, int y, char ch, uint32_t color, int scale) {
  unsigned idx = (unsigned)(uint8_t) ch;
  if (idx < FONT_FIRST || idx > FONT_LAST) return;

  const uint8_t *g = GLYPHS[idx - FONT_FIRST];

  for (int row = 0; row < FONT_GLYPH_H; row++) {
    for (int col = 0; col < FONT_GLYPH_W; col++) {
      if (g[row] & (uint8_t)(0x10u >> (unsigned) col)) {
        graphics_draw_rectangle(
          (uint16_t)(x + col * scale),
          (uint16_t)(y + row * scale),
          (uint16_t) scale,
          (uint16_t) scale,
          color);
      }
    }
  }
}

void font_draw_string(int x, int y, const char *str, uint32_t color, int scale) {
  if (str == NULL) return;
  int cx = x;
  for (int i = 0; str[i] != '\0'; i++) {
    font_draw_char(cx, y, str[i], color, scale);
    cx += (FONT_GLYPH_W + FONT_SPACING) * scale;
  }
}

int font_string_width(const char *str, int scale) {
  if (str == NULL) return 0;
  int len = 0;
  for (int i = 0; str[i] != '\0'; i++) len++;
  if (len == 0) return 0;
  /* Total = (chars × step) − last spacing */
  return len * (FONT_GLYPH_W + FONT_SPACING) * scale - FONT_SPACING * scale;
}
